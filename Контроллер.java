import java.util.List;

public class Контроллер {
    private final ПотокСервис сервис;

    public Контроллер(ПотокСервис сервис) {
        this.сервис = сервис;
    }

    public void отсортироватьИВывести(List<Поток> потоки) {
        сервис.отсортироватьПотоки(потоки);
        System.out.println(" Потоки отсортированы:");
        for (Поток поток : потоки) {
            System.out.println(поток);
        }
    }
}
